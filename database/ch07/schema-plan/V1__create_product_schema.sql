SET ROLE northstar_owner;

CREATE SCHEMA northstar AUTHORIZATION northstar_owner;

CREATE TABLE northstar.product (
    product_id bigint GENERATED BY DEFAULT AS IDENTITY,
    name varchar(120) NOT NULL,
    description varchar(1000),
    price numeric NOT NULL,
    active boolean NOT NULL DEFAULT true,
    CONSTRAINT product_pk PRIMARY KEY (product_id),
    CONSTRAINT product_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT product_price_minimum CHECK (price >= 0.01),
    CONSTRAINT product_price_finite CHECK (price NOT IN ('NaN'::numeric, 'Infinity'::numeric, '-Infinity'::numeric)),
    CONSTRAINT product_price_scale CHECK (min_scale(price) <= 2)
);

GRANT USAGE ON SCHEMA northstar TO northstar_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE northstar.product TO northstar_app;
GRANT USAGE, SELECT ON SEQUENCE northstar.product_product_id_seq TO northstar_app;

ALTER DEFAULT PRIVILEGES FOR ROLE northstar_owner IN SCHEMA northstar
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO northstar_app;
ALTER DEFAULT PRIVILEGES FOR ROLE northstar_owner IN SCHEMA northstar
    GRANT USAGE, SELECT ON SEQUENCES TO northstar_app;

RESET ROLE;
